const (
	// NonceHTMLPlaceholder is the placeholder for nonce in HTML script tags
	NonceHTMLPlaceholder = "__CSP_NONCE_VALUE__"

	// SEO placeholders
	SEOTitlePlaceholder       = "__SEO_TITLE__"
	SEODescriptionPlaceholder = "__SEO_DESCRIPTION__"
	SEOImagePlaceholder       = "__SEO_IMAGE__"

	// Default SEO values
	DefaultSEOTitle       = "Sub2API - AI Coding Relay"
	DefaultSEODescription = "One API key for Claude Code, Codex CLI, Gemini CLI, and Cursor — transparent billing, real-time usage, and safety limits."
	DefaultSEOImage       = "/logo.png"
)

//go:embed all:dist
var frontendFS embed.FS

// PublicSettingsProvider is an interface to fetch public settings
type PublicSettingsProvider interface {
	GetPublicSettingsForInjection(ctx context.Context) (any, error)
}

// FrontendServer serves the embedded frontend with settings injection
type FrontendServer struct {
	distFS      fs.FS
	fileServer  http.Handler
	baseHTML    []byte
	cache       *HTMLCache
	settings    PublicSettingsProvider
	overrideDir string // local file override directory
}

// NewFrontendServer creates a new frontend server with settings injection
func NewFrontendServer(settingsProvider PublicSettingsProvider) (*FrontendServer, error) {
	distFS, err := fs.Sub(frontendFS, "dist")
	if err != nil {
		return nil, err
	}

	// Read base HTML once
	file, err := distFS.Open("index.html")
	if err != nil {
		return nil, err
	}
	defer func() { _ = file.Close() }()

	baseHTML, err := io.ReadAll(file)
	if err != nil {
		return nil, err
	}

	cache := NewHTMLCache()
	cache.SetBaseHTML(baseHTML)

	return &FrontendServer{
		distFS:      distFS,
		fileServer:  http.FileServer(http.FS(distFS)),
		baseHTML:    baseHTML,
		cache:       cache,
		settings:    settingsProvider,
		overrideDir: filepath.Join("data", "public"),
	}, nil
}

// InvalidateCache invalidates the HTML cache (call when settings change)
func (s *FrontendServer) InvalidateCache() {
	if s != nil && s.cache != nil {
		s.cache.Invalidate()
	}
}

// InvalidateDomainCache invalidates cache for a specific reseller domain
func (s *FrontendServer) InvalidateDomainCache(domain string) {
	if s != nil && s.cache != nil {
		s.cache.InvalidateDomain(domain)
	}
}

// Middleware returns the Gin middleware handler
func (s *FrontendServer) Middleware() gin.HandlerFunc {
	return func(c *gin.Context) {
		path := c.Request.URL.Path

		// Skip API routes
		if shouldBypassEmbeddedFrontend(path) {
			c.Next()
			return
		}

		cleanPath := strings.TrimPrefix(path, "/")
		if cleanPath == "" {
			cleanPath = "index.html"
		}

		// For index.html or SPA routes, serve with injected settings
		if cleanPath == "index.html" || !s.fileExists(cleanPath) {
			s.serveIndexHTML(c)
			return
		}

		// Try local override first
		if s.tryServeOverride(c, cleanPath) {
			return
		}

		// Serve static files normally (hashed assets get long-lived cache headers)
		applyStaticAssetCacheHeaders(c.Writer.Header(), cleanPath)
		s.fileServer.ServeHTTP(c.Writer, c.Request)
		c.Abort()
	}
}

func (s *FrontendServer) fileExists(path string) bool {
	file, err := s.distFS.Open(path)
	if err != nil {
		return false
	}
	_ = file.Close()
	return true
}

// tryServeOverride checks if a local override file exists and serves it.
// Files in overrideDir take precedence over embedded files.
func (s *FrontendServer) tryServeOverride(c *gin.Context, cleanPath string) bool {
	if s.overrideDir == "" {
		return false
	}
	filePath := filepath.Join(s.overrideDir, filepath.Clean("/"+cleanPath))
	info, err := os.Stat(filePath)
	if err != nil || info.IsDir() {
		return false
	}
	c.File(filePath)
	c.Abort()
	return true
}

func (s *FrontendServer) serveIndexHTML(c *gin.Context) {
	// Get nonce from context (generated by SecurityHeaders middleware)
	nonce := middleware.GetNonceFromContext(c)

	// Determine cache key from reseller domain context
	cacheKey := "" // default site
	resellerDomain := middleware.GetResellerDomainFromContext(c)
	if resellerDomain != nil {
		cacheKey = resellerDomain.Domain
	}

	// Check cache first
	cached := s.cache.Get(cacheKey)
	if cached != nil {
		// Check If-None-Match for 304 response
		if match := c.GetHeader("If-None-Match"); match == cached.ETag {
			c.Status(http.StatusNotModified)
			c.Abort()
			return
		}

		// Replace nonce placeholder with actual nonce before serving
		content := replaceNoncePlaceholder(cached.Content, nonce)

		c.Header("ETag", cached.ETag)
		c.Header("Cache-Control", "no-cache") // Must revalidate
		c.Data(http.StatusOK, "text/html; charset=utf-8", content)
		c.Abort()
		return
	}

	// Cache miss - fetch settings and render
	ctx, cancel := context.WithTimeout(c.Request.Context(), 2*time.Second)
	defer cancel()

	settings, err := s.settings.GetPublicSettingsForInjection(ctx)
	if err != nil {
		// Fallback: serve without injection
		c.Data(http.StatusOK, "text/html; charset=utf-8", s.baseHTML)
		c.Abort()
		return
	}

	settingsJSON, err := json.Marshal(settings)
	if err != nil {
		// Fallback: serve without injection
		c.Data(http.StatusOK, "text/html; charset=utf-8", s.baseHTML)
		c.Abort()
		return
	}

	// If this is a reseller domain, merge reseller branding into settings
	if resellerDomain != nil {
		settingsJSON = mergeResellerBranding(settingsJSON, resellerDomain)
	}

	rendered := s.injectSettings(settingsJSON, cacheKey)
	s.cache.Set(cacheKey, rendered, settingsJSON)

	// Replace nonce placeholder with actual nonce before serving
	content := replaceNoncePlaceholder(rendered, nonce)

	cached = s.cache.Get(cacheKey)
	if cached != nil {
		c.Header("ETag", cached.ETag)
	}
	c.Header("Cache-Control", "no-cache")
	c.Data(http.StatusOK, "text/html; charset=utf-8", content)
	c.Abort()
}

// mergeResellerBranding overlays reseller branding onto the base public settings JSON.
// It overrides site_name, site_logo, etc. and adds reseller_id for frontend auto-registration.
func mergeResellerBranding(baseJSON []byte, info *middleware.ResellerDomainContext) []byte {
	var m map[string]any
	if err := json.Unmarshal(baseJSON, &m); err != nil {
		return baseJSON
	}

	// Add reseller-specific fields
	m["reseller_id"] = info.ResellerID
	m["reseller_domain"] = info.Domain

	// 商户自定义域名作为 API 端点 base URL：让该商户的子用户在 API Key / 密钥查询 /
	// 接入文档页看到的端点是商户自己的域名（而非主站 mayi.one）。
	// 隔离天然成立：本函数仅在 DomainDetect 按 Host 识别到「已验证」的 reseller 域名时调用，
	// 主站访问不经过这里（主站端点不受影响），不同商户各自按自己的 Host 注入（互不可见）。
	if info.Domain != "" {
		m["api_base_url"] = "https://" + info.Domain
	}

	// Override branding from domain-level settings (per-domain)
	if info.SiteName != "" {
		m["site_name"] = info.SiteName
	}
	if info.SiteLogo != "" {
		m["site_logo"] = info.SiteLogo
	}
	if info.BrandColor != "" {
		m["brand_color"] = info.BrandColor
	}
	if info.CustomCSS != "" {
		m["custom_css"] = info.CustomCSS
	}
	if info.Subtitle != "" {
		m["site_subtitle"] = info.Subtitle
	}
	if info.HomeContent != "" {
		m["home_content"] = info.HomeContent
	}
	// For reseller domains: only show doc_url and purchase if the reseller explicitly set them.
	// Clear system defaults so the frontend can hide links the reseller didn't configure.
	if info.DocURL != "" {
		m["doc_url"] = info.DocURL
	} else {
		delete(m, "doc_url")
	}
	if info.HomeTemplate != "" {
		m["home_template"] = info.HomeTemplate
	}
	// Reseller 域名只展示 reseller 自己配置的购买入口
	if info.PurchaseEnabled {
		m["purchase_enabled"] = true
		if info.PurchaseURL != "" {
			m["purchase_url"] = info.PurchaseURL
		}
	} else {
		delete(m, "purchase_enabled")
		delete(m, "purchase_url")
	}
	if info.SEOTitle != "" {
		m["seo_title"] = info.SEOTitle
	}
	if info.SEODescription != "" {
		m["seo_description"] = info.SEODescription
	}
	if info.SEOKeywords != "" {
		m["seo_keywords"] = info.SEOKeywords
	}
	if info.LoginRedirect != "" {
		m["login_redirect"] = info.LoginRedirect
	}

	// Reseller sites are isolated from main site contact info
	delete(m, "contact_info")
	delete(m, "contact_wechat")
	delete(m, "contact_telegram")
	delete(m, "contact_qq")
	// 主站的余额提醒充值链接不下发给商户站点（商户用户不应被引导到主站充值；
	// 该字段在用户侧前端无消费方，真正用它的是后端邮件模板，删除无副作用）
	delete(m, "balance_low_notify_recharge_url")

	// Override from reseller-global settings (contact_info, default_locale, etc.)
	if rs := info.ResellerSettings; rs != nil {
		if v := rs["contact_info"]; v != "" {
			m["contact_info"] = v
		}
		if v := rs["default_locale"]; v != "" {
			m["default_locale"] = v
		}
		if v := rs["contact_wechat"]; v != "" {
			m["contact_wechat"] = v
		}
		if v := rs["contact_telegram"]; v != "" {
			m["contact_telegram"] = v
		}
		if v := rs["contact_qq"]; v != "" {
			m["contact_qq"] = v
		}
		// 访问控制：把商户站点的注册/登录开关暴露给前端，用于隐藏首页入口
		if rs["reseller_registration_disabled"] == "true" {
			m["reseller_registration_disabled"] = true
		}
		if rs["reseller_login_disabled"] == "true" {
			m["reseller_login_disabled"] = true
		}
		// When merchant_mode is enabled, expose the payment page using reseller's own pay_url.
		if rs["merchant_mode"] == "enabled" {
			m["reseller_agent_enabled"] = true
			if payURL := rs["pay_url"]; payURL != "" {
				m["purchase_enabled"] = true
				m["purchase_url"] = payURL
			}
		}
	}

	// Domain-level default_locale overrides reseller-global default_locale
	if info.DefaultLocale != "" {
		m["default_locale"] = info.DefaultLocale
	}

	// Replace system announcements with reseller's own SimpleAnnouncements (if any).
	delete(m, "announcements")
	if rs := info.ResellerSettings; rs != nil {
		if v := rs["announcements"]; v != "" {
			var arr []any
			if json.Unmarshal([]byte(v), &arr) == nil && len(arr) > 0 {
				m["announcements"] = arr
			}
		}
	}

	result, err := json.Marshal(m)
	if err != nil {
		return baseJSON
	}
	return result
}

// seoSettings is used to extract SEO-related fields from settings JSON
type seoSettings struct {
	SiteName       string `json:"site_name"`
	SiteSubtitle   string `json:"site_subtitle"`
	SiteLogo       string `json:"site_logo"`
	SEOTitle       string `json:"seo_title"`
	SEODescription string `json:"seo_description"`
	SEOKeywords    string `json:"seo_keywords"`
}

// injectSettings renders index.html with the given public settings.
// resellerHost is the reseller custom domain ("" for the main site); when set,
// the hardcoded main-site SEO tags in the build output are rewritten so the
// raw HTML served on reseller domains never leaks main-site URLs or copy.
func (s *FrontendServer) injectSettings(settingsJSON []byte, resellerHost string) []byte {
	// Start with base HTML
	result := s.baseHTML

	// Extract SEO values from settings
	var seo seoSettings
	seoOK := json.Unmarshal(settingsJSON, &seo) == nil

	seoTitle := DefaultSEOTitle
	seoDesc := DefaultSEODescription
	seoImage := DefaultSEOImage
	if seoOK {
		// Build SEO title: prefer explicit seo_title, then "SiteName - SiteSubtitle", then default
		if seo.SEOTitle != "" {
			seoTitle = seo.SEOTitle
		} else if seo.SiteName != "" {
			if seo.SiteSubtitle != "" {
				seoTitle = seo.SiteName + " - " + seo.SiteSubtitle
			} else {
				seoTitle = seo.SiteName
			}
		}

		// SEO description: prefer explicit seo_description, then subtitle, then default
		if seo.SEODescription != "" {
			seoDesc = seo.SEODescription
		} else if seo.SiteSubtitle != "" {
			seoDesc = seo.SiteSubtitle
		}

		// SEO image: use logo or default
		if seo.SiteLogo != "" {
			seoImage = seo.SiteLogo
		}

		// Replace SEO placeholders
		result = bytes.ReplaceAll(result, []byte(SEOTitlePlaceholder), []byte(seoTitle))
		result = bytes.ReplaceAll(result, []byte(SEODescriptionPlaceholder), []byte(seoDesc))
		result = bytes.ReplaceAll(result, []byte(SEOImagePlaceholder), []byte(seoImage))
	}

	// Apply custom branding before the browser paints the static defaults.
	result = injectSiteTitle(result, settingsJSON)
	result = injectSiteFavicon(result, settingsJSON)

	// 商户域名：index.html 构建产物里写死了主站的 canonical/hreflang/og/twitter/JSON-LD。
	// 链接预览与搜索爬虫大多不执行 JS，运行时 applySeoMeta 救不了原始 HTML，
	// 必须在服务端把主站域名和文案替换成商户自己的，避免商户站点泄露主站内容。
	if resellerHost != "" && seoOK {
		result = rewriteResellerSEO(result, resellerHost, seo, seoTitle, seoDesc, seoImage)
	}

	// Inject settings script before </head>; the nonce placeholder is replaced
	// with the per-request nonce at serve time.
	script := []byte(`<script nonce="` + NonceHTMLPlaceholder + `">window.__APP_CONFIG__=` + string(settingsJSON) + `;</script>`)
	headClose := []byte("</head>")
	result = bytes.Replace(result, headClose, append(script, headClose...), 1)

	return result
}

var (
	reCanonicalHref = regexp.MustCompile(`<link rel="canonical" href="([^"]*)"`)
	reMetaDesc      = regexp.MustCompile(`(<meta name="description" content=")[^"]*(")`)
	reMetaKeywords  = regexp.MustCompile(`(<meta\s+name="keywords"\s+content=")[^"]*(")`)
	reOGTitle       = regexp.MustCompile(`(<meta property="og:title" content=")[^"]*(")`)
	reOGDesc        = regexp.MustCompile(`(<meta property="og:description" content=")[^"]*(")`)
	reOGImage       = regexp.MustCompile(`(<meta property="og:image" content=")[^"]*(")`)
	reTwitterTitle  = regexp.MustCompile(`(<meta name="twitter:title" content=")[^"]*(")`)
	reTwitterDesc   = regexp.MustCompile(`(<meta name="twitter:description" content=")[^"]*(")`)
	reTwitterImage  = regexp.MustCompile(`(<meta name="twitter:image" content=")[^"]*(")`)
	reStructuredLD  = regexp.MustCompile(`(?s)(<script id="structured-data" type="application/ld\+json">).*?(</script>)`)
)

// replaceTagContent rewrites the content attribute matched by re with value,
// escaping it for the double-quoted HTML attribute context.
func replaceTagContent(htmlBytes []byte, re *regexp.Regexp, value string) []byte {
	escaped := strings.ReplaceAll(htmlpkg.EscapeString(value), "$", "$$")
	return re.ReplaceAll(htmlBytes, []byte("${1}"+escaped+"${2}"))
}

// rewriteResellerSEO replaces the main-site SEO tags baked into index.html
// with the reseller's own domain and branding.
func rewriteResellerSEO(result []byte, host string, seo seoSettings, seoTitle, seoDesc, seoImage string) []byte {
	origin := "https://" + host

	// 主站 origin 从 canonical 标签里解析（不在 Go 侧硬编码主站域名），
	// 整体替换后 canonical/hreflang/preconnect/dns-prefetch/og:url 全部指向商户域名。
	if m := reCanonicalHref.FindSubmatch(result); m != nil {
		if u, err := url.Parse(string(m[1])); err == nil && u.Scheme != "" && u.Host != "" {
			mainOrigin := u.Scheme + "://" + u.Host
			if mainOrigin != origin {
				result = bytes.ReplaceAll(result, []byte(mainOrigin), []byte(origin))
			}
		}
	}

	// 分享图用商户配置的 logo；相对路径补成商户域名的绝对地址，
	// data: URI 无法用于 og:image，回退到 /logo.png。
	imageURL := seoImage
	switch {
	case strings.HasPrefix(imageURL, "http://"), strings.HasPrefix(imageURL, "https://"):
	case strings.HasPrefix(imageURL, "/"):
		imageURL = origin + imageURL
	default:
		imageURL = origin + "/logo.png"
	}

	result = replaceTitleTag(result, seoTitle)
	result = replaceTagContent(result, reMetaDesc, seoDesc)
	result = replaceTagContent(result, reMetaKeywords, seo.SEOKeywords)
	result = replaceTagContent(result, reOGTitle, seoTitle)
	result = replaceTagContent(result, reOGDesc, seoDesc)
	result = replaceTagContent(result, reOGImage, imageURL)
	result = replaceTagContent(result, reTwitterTitle, seoTitle)
	result = replaceTagContent(result, reTwitterDesc, seoDesc)
	result = replaceTagContent(result, reTwitterImage, imageURL)

	// JSON-LD 整体重建为商户站点信息（运行时 applySeoMeta 还会按路由细化）
	siteName := seo.SiteName
	if siteName == "" {
		siteName = seoTitle
	}
	ld := map[string]any{
		"@context":    "https://schema.org",
		"@type":       "WebSite",
		"name":        siteName,
		"url":         origin + "/",
		"description": seoDesc,
		"image":       imageURL,
	}
	// json.Marshal 默认转义 <>&，注入 <script> 上下文安全
	if b, err := json.Marshal(ld); err == nil {
		escaped := strings.ReplaceAll(string(b), "$", "$$")
		result = reStructuredLD.ReplaceAll(result, []byte("${1}"+escaped+"${2}"))
	}

	return result
}

// replaceTitleTag replaces the <title> text with the given value.
func replaceTitleTag(htmlBytes []byte, title string) []byte {
	start := bytes.Index(htmlBytes, []byte("<title>"))
	end := bytes.Index(htmlBytes, []byte("</title>"))
	if start == -1 || end == -1 || end <= start {
		return htmlBytes
	}
	var buf bytes.Buffer
	buf.Write(htmlBytes[:start])
	buf.WriteString("<title>")
	buf.WriteString(htmlpkg.EscapeString(title))
	buf.Write(htmlBytes[end:])
	return buf.Bytes()
}

// injectSiteFavicon replaces the static favicon with a configured, browser-safe image URL.
func injectSiteFavicon(html, settingsJSON []byte) []byte {
	var cfg struct {
		SiteLogo string `json:"site_logo"`
	}
	if err := json.Unmarshal(settingsJSON, &cfg); err != nil {
		return html
	}

	logoURL := safeImageURL(cfg.SiteLogo)
	if logoURL == "" {
		return html
	}

	linkStart := bytes.Index(html, []byte(`<link rel="icon"`))
	if linkStart == -1 {
		return html
	}
	linkEndOffset := bytes.IndexByte(html[linkStart:], '>')
	if linkEndOffset == -1 {
		return html
	}
	linkEnd := linkStart + linkEndOffset + 1
	replacement := []byte(`<link rel="icon" href="` + htmlpkg.EscapeString(logoURL) + `" />`)

	var buf bytes.Buffer
	buf.Write(html[:linkStart])
	buf.Write(replacement)
	buf.Write(html[linkEnd:])
	return buf.Bytes()
}

func safeImageURL(value string) string {
	trimmed := strings.TrimSpace(value)
	if trimmed == "" {
		return ""
	}
	if strings.HasPrefix(trimmed, "/") && !strings.HasPrefix(trimmed, "//") {
		return trimmed
	}
	if strings.HasPrefix(strings.ToLower(trimmed), "data:image/") {
		return trimmed
	}

	parsed, err := url.Parse(trimmed)
	if err != nil || (parsed.Scheme != "http" && parsed.Scheme != "https") || parsed.Host == "" {
		return ""
	}
	return trimmed
}

// injectSiteTitle replaces the static <title> in HTML with the configured site name.
// This ensures the browser tab shows the correct title before JS executes.
func injectSiteTitle(html, settingsJSON []byte) []byte {
	var cfg struct {
		SiteName string `json:"site_name"`
	}
	if err := json.Unmarshal(settingsJSON, &cfg); err != nil || cfg.SiteName == "" {
		return html
	}

	// Find and replace the existing <title>...</title>
	titleStart := bytes.Index(html, []byte("<title>"))
	titleEnd := bytes.Index(html, []byte("</title>"))
	if titleStart == -1 || titleEnd == -1 || titleEnd <= titleStart {
		return html
	}

	newTitle := []byte("<title>" + htmlpkg.EscapeString(cfg.SiteName) + " - AI API Gateway</title>")
	var buf bytes.Buffer
	buf.Write(html[:titleStart])
	buf.Write(newTitle)
	buf.Write(html[titleEnd+len("</title>"):])
	return buf.Bytes()
}

// replaceNoncePlaceholder replaces the nonce placeholder with actual nonce value
func replaceNoncePlaceholder(html []byte, nonce string) []byte {
	return bytes.ReplaceAll(html, []byte(NonceHTMLPlaceholder), []byte(nonce))
}

// ServeEmbeddedFrontend returns a middleware for serving embedded frontend
// This is the legacy function for backward compatibility when no settings provider is available
func ServeEmbeddedFrontend() gin.HandlerFunc {
	distFS, err := fs.Sub(frontendFS, "dist")
	if err != nil {
		panic("failed to get dist subdirectory: " + err.Error())
	}
	fileServer := http.FileServer(http.FS(distFS))
	overrideDir := filepath.Join("data", "public")

	return func(c *gin.Context) {
		path := c.Request.URL.Path

		if shouldBypassEmbeddedFrontend(path) {
			c.Next()
			return
		}

		cleanPath := strings.TrimPrefix(path, "/")
		if cleanPath == "" {
			cleanPath = "index.html"
		}

		if file, err := distFS.Open(cleanPath); err == nil {
			_ = file.Close()
			// Try local override first
			if tryServeOverrideFile(c, overrideDir, cleanPath) {
				return
			}
			applyStaticAssetCacheHeaders(c.Writer.Header(), cleanPath)
			fileServer.ServeHTTP(c.Writer, c.Request)
			c.Abort()
			return
		}

		serveIndexHTML(c, distFS)
	}
}

// tryServeOverrideFile is a standalone version of tryServeOverride for legacy usage.
func tryServeOverrideFile(c *gin.Context, overrideDir, cleanPath string) bool {
	if overrideDir == "" {
		return false
	}
	filePath := filepath.Join(overrideDir, filepath.Clean("/"+cleanPath))
	info, err := os.Stat(filePath)
	if err != nil || info.IsDir() {
		return false
	}
	c.File(filePath)
	c.Abort()
	return true
}

func shouldBypassEmbeddedFrontend(path string) bool {
	trimmed := strings.TrimSpace(path)
	return strings.HasPrefix(trimmed, "/api/") ||
		strings.HasPrefix(trimmed, "/v1/") ||
		strings.HasPrefix(trimmed, "/v1beta/") ||
		strings.HasPrefix(trimmed, "/backend-api/") ||
		strings.HasPrefix(trimmed, "/antigravity/") ||
		strings.HasPrefix(trimmed, "/setup/") ||
		trimmed == "/health" ||
		trimmed == "/models" ||
		trimmed == "/responses" ||
		strings.HasPrefix(trimmed, "/responses/") ||
		trimmed == "/alpha/search" ||
		strings.HasPrefix(trimmed, "/images/") ||
		strings.HasPrefix(trimmed, "/videos/")
}

func serveIndexHTML(c *gin.Context, fsys fs.FS) {
	file, err := fsys.Open("index.html")
	if err != nil {
		c.String(http.StatusNotFound, "Frontend not found")
		c.Abort()
		return
	}
	defer func() { _ = file.Close() }()

	content, err := io.ReadAll(file)
	if err != nil {
		c.String(http.StatusInternalServerError, "Failed to read index.html")
		c.Abort()
		return
	}

	c.Data(http.StatusOK, "text/html; charset=utf-8", content)
	c.Abort()
}

func HasEmbeddedFrontend() bool {
	_, err := frontendFS.ReadFile("dist/index.html")
	return err == nil
}
